package me.helvert.codebridge.rpc

import com.intellij.openapi.progress.ProcessCanceledException
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.channels.Channel
import kotlinx.coroutines.currentCoroutineContext
import kotlinx.coroutines.ensureActive
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.buffer
import kotlinx.coroutines.flow.channelFlow
import kotlinx.coroutines.flow.flowOn
import java.nio.file.Files
import java.nio.file.Path
import kotlin.coroutines.CoroutineContext

/**
 * What an [operationFlow] says it is doing, each change sent as an update: its [text], and how far
 * along it is as a [fraction], `null` while that is not known.
 */
class OperationProgress internal constructor(
    private val context: CoroutineContext,
    private val publish: (OperationUpdate) -> Unit,
) {
    var text: String = ""
        set(value) {
            field = value; publish(OperationUpdate(value, fraction))
        }

    var fraction: Double? = null
        set(value) {
            field = value; publish(OperationUpdate(text, value))
        }

    /** Throws once collection has been canceled; for blocking work, which cannot suspend to see it. */
    fun checkCanceled() = context.ensureActive()
}

/** A cold operation: collecting starts the work; canceling collection cancels it. */
fun operationFlow(work: suspend (OperationProgress) -> InstallResultDto?): Flow<OperationUpdate> = channelFlow {
    val progress = OperationProgress(currentCoroutineContext()) { trySend(it) }
    try {
        progress.checkCanceled()
        val result = work(progress)
        send(OperationUpdate(completed = true, result = result))
    } catch (cancelled: CancellationException) {
        throw cancelled
    } catch (cancelled: ProcessCanceledException) {
        throw cancelled
    } catch (error: Exception) {
        send(OperationUpdate(error = error.message ?: error.javaClass.simpleName))
    }
}.buffer(Channel.CONFLATED).flowOn(Dispatchers.IO)

/** The only filename used on disk is generated by the backend, never supplied by the client. */
@Suppress("BlockingMethodInNonBlockingContext") // collected in operationFlow, on Dispatchers.IO
internal suspend fun <T> withUploadedVsix(
    contents: Flow<ByteArray>,
    checkCanceled: () -> Unit,
    parent: Path? = null,
    install: (Path) -> T,
): T {
    val directory = if (parent == null) Files.createTempDirectory("codebridge-upload")
    else Files.createTempDirectory(parent, "codebridge-upload")
    try {
        val file = directory.resolve("extension.vsix")
        Files.newOutputStream(file).use { output ->
            contents.collect { bytes ->
                currentCoroutineContext().ensureActive()
                checkCanceled()
                output.write(bytes)
            }
        }
        checkCanceled()
        return install(file)
    } finally {
        deleteTransferDirectory(directory)
    }
}

/** Only called with a private directory freshly allocated by these transfer operations. */
fun deleteTransferDirectory(directory: Path) {
    Files.walk(directory).use { paths ->
        paths.sorted(Comparator.reverseOrder()).forEach { Files.deleteIfExists(it) }
    }
}
